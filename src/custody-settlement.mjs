import { PublicKey } from '@solana/web3.js'
import bs58 from 'bs58'
import { CP_AMM_PROGRAM_ID, derivePoolAuthority } from '@meteora-ag/cp-amm-sdk'
import { NATIVE_MINT, TOKEN_PROGRAM_ID, TOKEN_2022_PROGRAM_ID, getAssociatedTokenAddressSync,
  ASSOCIATED_TOKEN_PROGRAM_ID, createAssociatedTokenAccountIdempotentInstruction, createTransferCheckedInstruction } from '@solana/spl-token'
import { prepareCustodyMultisig, validateCustodyGovernance } from './custody-multisig.mjs'
import { validateDbcCustodyBatchReceipt } from './custody-dbc-receipt.mjs'
export { validateDbcCustodyBatchReceipt }

export const CUSTODY_VAULT = '3dHCTpgdx15yXyVGh7DK1woQ1XisQpmFCxncURrq63Gs'
const pk = value => new PublicKey(value)
const address = value => pk(value).toBase58()
const fail = () => { throw Error('Custody receipt/preparation mismatch or unsupported evidence; review required') }
const requireThat = condition => { if (!condition) fail() }
const claimTag = Buffer.from([180,38,154,17,133,33,162,211])
const eventTag = Buffer.from('e445a52e51cb9a1dc6b6b734610c3138', 'hex')
const canonical = ix => ({ program: address(ix.programId), accounts: ix.keys.map(k => address(k.pubkey)), data: Buffer.from(ix.data).toString('hex') })

// OFFLINE ONLY. Inputs must come from the explicitly custody-aware, verified graduated
// reader. Attribution is historical metadata, not authorization or beneficiary payment.
// No helper that unwraps SOL, ephemeral keys, RPC, signing, or execution is used here.
export async function prepareCustodySettlement({ amm, pool, position, nftAccount, poolState,
  tokenAProgram, payer, createAtas = false, attribution }) {
  requireThat(poolState?.collectFeeMode === 1 && address(poolState.tokenBMint) === NATIVE_MINT.toBase58())
  requireThat([TOKEN_PROGRAM_ID.toBase58(), TOKEN_2022_PROGRAM_ID.toBase58()].includes(address(tokenAProgram)))
  requireThat(attribution && ['creator', 'partner'].includes(attribution.role) && attribution.repoId && attribution.migration)
  requireThat(address(attribution.previousOwner) !== CUSTODY_VAULT)
  const owner = pk(CUSTODY_VAULT)
  const tokenAAccount = getAssociatedTokenAddressSync(pk(poolState.tokenAMint), owner, true, pk(tokenAProgram))
  const tokenBAccount = getAssociatedTokenAddressSync(NATIVE_MINT, owner, true, TOKEN_PROGRAM_ID)
  const eventAuthority = PublicKey.findProgramAddressSync([Buffer.from('__event_authority')], CP_AMM_PROGRAM_ID)[0]
  const claimInstruction = await amm._program.methods.claimPositionFee().accountsStrict({
    poolAuthority: derivePoolAuthority(), pool: pk(pool), position: pk(position),
    tokenAAccount, tokenBAccount, tokenAVault: pk(poolState.tokenAVault), tokenBVault: pk(poolState.tokenBVault),
    tokenAMint: pk(poolState.tokenAMint), tokenBMint: NATIVE_MINT, positionNftAccount: pk(nftAccount),
    signer: owner, tokenAProgram: pk(tokenAProgram), tokenBProgram: TOKEN_PROGRAM_ID,
    eventAuthority, program: CP_AMM_PROGRAM_ID,
  }).instruction()
  requireThat(claimInstruction.programId.equals(CP_AMM_PROGRAM_ID) && claimInstruction.data.equals(claimTag))
  const instructions = createAtas ? [
    createAssociatedTokenAccountIdempotentInstruction(pk(payer), tokenAAccount, owner, pk(poolState.tokenAMint), pk(tokenAProgram)),
    createAssociatedTokenAccountIdempotentInstruction(pk(payer), tokenBAccount, owner, NATIVE_MINT, TOKEN_PROGRAM_ID),
    claimInstruction,
  ] : [claimInstruction]
  return { instructions, claimInstruction, destination: tokenBAccount.toBase58(), pool: address(pool), position: address(position),
    owner: CUSTODY_VAULT, attribution: Object.freeze({ ...attribution }), beneficiaryPaid: false }
}

// Trust boundary: tx and finality MUST be independently obtained from trusted finalized
// RPC (not simulation or user JSON). review is an independently reviewed exact execution
// transcript, NOT generated by copying tx inside an untrusted settlement request. It binds
// every outer/inner instruction including data and order. This deliberately bounded API
// rejects ALTs, parsed instructions, missing stack heights, multiple claims, and
// top-level PDA claims. Raw Squads governance evidence is mandatory. New ATAs need
// an approved idempotent create AND zero pre-lamports, never a guessed zero balance.
export function validateCustodyReceipt({ plan, tx, finality, review, multisigPlan, governanceProof }) {
  tx = normalizeReceiptTx(tx)
  requireThat(plan?.attribution?.repoId && ['creator', 'partner'].includes(plan.attribution.role) && plan.attribution.migration &&
    address(plan.attribution.previousOwner) !== CUSTODY_VAULT)
  requireThat(plan.destination === getAssociatedTokenAddressSync(NATIVE_MINT, pk(CUSTODY_VAULT), true).toBase58())
  requireThat(plan.instructions.length === 1 || plan.instructions.length === 3)
  requireThat(same(canonical(plan.instructions.at(-1)), canonical(plan.claimInstruction)))
  const claimKeys = plan.claimInstruction.keys
  requireThat(claimKeys.length === 15)
  requireThat(plan.attribution.position === plan.position && plan.attribution.mint === address(claimKeys[7].pubkey))
  if (plan.attribution.pool) requireThat(plan.attribution.pool === plan.pool)
  if (plan.attribution.nftAccount) requireThat(plan.attribution.nftAccount === address(claimKeys[9].pubkey))
  if (plan.instructions.length === 3) {
    const expectedAtas = [
      createAssociatedTokenAccountIdempotentInstruction(plan.instructions[0].keys[0].pubkey, claimKeys[3].pubkey, pk(CUSTODY_VAULT), claimKeys[7].pubkey, claimKeys[11].pubkey),
      createAssociatedTokenAccountIdempotentInstruction(plan.instructions[1].keys[0].pubkey, pk(plan.destination), pk(CUSTODY_VAULT), NATIVE_MINT),
    ]
    requireThat(same(plan.instructions.slice(0, 2).map(canonical), expectedAtas.map(canonical)))
  }
  const governance = validateExecution({ plan, tx, finality, review, multisigPlan, governanceProof })
  requireThat(finality?.confirmationStatus === 'finalized' && finality.err === null && tx?.meta?.err === null &&
    Number.isSafeInteger(tx.slot) && tx.slot > 0 && tx.slot === finality.slot &&
    tx.transaction?.signatures?.[0] === finality.signature && typeof finality.signature === 'string' && finality.signature.length > 0)
  const message = tx.transaction.message
  requireThat(!message.addressTableLookups?.length && !tx.meta.loadedAddresses?.writable?.length && !tx.meta.loadedAddresses?.readonly?.length)
  requireThat(Array.isArray(message.accountKeys) && Array.isArray(message.instructions) && Array.isArray(review?.top) && Array.isArray(review.inner))
  const keys = message.accountKeys.map(address)
  requireThat(new Set(keys).size === keys.length)
  const decode = ix => {
    requireThat(Number.isInteger(ix.programIdIndex) && keys[ix.programIdIndex] && Array.isArray(ix.accounts) && typeof ix.data === 'string')
    requireThat(ix.accounts.every(i => Number.isInteger(i) && keys[i]))
    return { program: keys[ix.programIdIndex], accounts: ix.accounts.map(i => keys[i]), data: Buffer.from(bs58.decode(ix.data)).toString('hex') }
  }
  requireThat(same(message.instructions.map(decode), review.top.map(canonical)))
  requireThat(Array.isArray(tx.meta.innerInstructions) && tx.meta.innerInstructions.length === review.inner.length)
  const intended = canonical(plan.claimInstruction)
  requireThat(plan.owner === CUSTODY_VAULT && intended.program === CP_AMM_PROGRAM_ID.toBase58() && intended.data === claimTag.toString('hex') &&
    intended.accounts.length === 15 && intended.accounts[1] === plan.pool && intended.accounts[2] === plan.position &&
    intended.accounts[4] === plan.destination && intended.accounts[8] === NATIVE_MINT.toBase58() && intended.accounts[10] === CUSTODY_VAULT)
  requireThat(message.instructions.every(ix => decode(ix).program !== CP_AMM_PROGRAM_ID.toBase58()))
  let claims = 0, events = 0, amount
  const groups = new Set()
  for (let g = 0; g < review.inner.length; g++) {
    const actual = tx.meta.innerInstructions[g], expected = review.inner[g]
    requireThat(Number.isInteger(actual.index) && actual.index >= 0 && actual.index < message.instructions.length && !groups.has(actual.index))
    groups.add(actual.index)
    requireThat(actual.index === expected.index && actual.instructions.length === expected.instructions.length)
    let activeClaim = false
    for (let i = 0; i < actual.instructions.length; i++) {
      const ix = actual.instructions[i], decoded = decode(ix), reviewed = expected.instructions[i]
      requireThat(Number.isInteger(ix.stackHeight) && ix.stackHeight >= 2 && ix.stackHeight === reviewed.stackHeight && same(decoded, canonical(reviewed.instruction)))
      if (ix.stackHeight <= 2) activeClaim = false
      if (decoded.program !== CP_AMM_PROGRAM_ID.toBase58()) continue
      const data = Buffer.from(decoded.data, 'hex')
      if (same(decoded, intended)) {
        requireThat(ix.stackHeight === 2)
        claims++; activeClaim = true
      } else {
        requireThat(activeClaim && ix.stackHeight === 3 && data.length === 128 && data.subarray(0, 16).equals(eventTag))
        requireThat(address(data.subarray(16, 48)) === plan.pool && address(data.subarray(48, 80)) === plan.position &&
          address(data.subarray(80, 112)) === CUSTODY_VAULT && data.readBigUInt64LE(112) === 0n)
        amount = data.readBigUInt64LE(120); events++
      }
    }
  }
  requireThat(claims === 1 && events === 1 && amount > 0n)
  const balance = (rows, pre = false) => {
    requireThat(Array.isArray(rows))
    const matches = rows.filter(row => keys[row.accountIndex] === plan.destination)
    if (pre && matches.length === 0) {
      requireThat(approvedNewAta(plan, tx, keys, plan.destination))
      return 0n
    }
    requireThat(matches.length === 1)
    const row = matches[0]
    requireThat(row.owner === CUSTODY_VAULT && row.mint === NATIVE_MINT.toBase58() && row.programId === TOKEN_PROGRAM_ID.toBase58() &&
      row.uiTokenAmount?.decimals === 9 && /^(0|[1-9][0-9]*)$/.test(row.uiTokenAmount.amount))
    return BigInt(row.uiTokenAmount.amount)
  }
  requireThat(balance(tx.meta.postTokenBalances) - balance(tx.meta.preTokenBalances, true) === amount)
  return Object.freeze({ kind: 'vault-wsol-fee-collection', signature: finality.signature, slot: tx.slot, pool: plan.pool,
    position: plan.position, owner: CUSTODY_VAULT, destination: plan.destination, mint: NATIVE_MINT.toBase58(), amount,
    attribution: Object.freeze({ ...plan.attribution }), beneficiaryPaid: false, vaultControlVerified: true, governance })
}

const same = (a, b) => JSON.stringify(a) === JSON.stringify(b)
function approvedNewAta(plan, tx, keys, destination) {
  const i = keys.indexOf(destination)
  return i >= 0 && tx.meta.preBalances?.[i] === 0 && Number.isSafeInteger(tx.meta.postBalances?.[i]) && tx.meta.postBalances[i] > 0 &&
    plan.instructions.some(ix => ix.programId.equals(ASSOCIATED_TOKEN_PROGRAM_ID) && ix.data.equals(Buffer.from([1])) &&
      address(ix.keys[1].pubkey) === destination)
}

function validateExecution({ plan, tx, finality, review, multisigPlan, governanceProof }) {
  requireThat(finality?.confirmationStatus === 'finalized' && finality.err === null && tx?.meta?.err === null &&
    Number.isSafeInteger(tx.slot) && tx.slot > 0 && tx.slot === finality.slot &&
    tx.transaction?.signatures?.[0] === finality.signature && typeof finality.signature === 'string' && finality.signature.length > 0)
  requireThat(multisigPlan && same(plan.instructions.map(canonical), multisigPlan.instructions.map(canonical)))
  const governance = validateCustodyGovernance({ plan: multisigPlan, proof: governanceProof, slot: tx.slot, signature: finality.signature })
  const expected = prepareCustodyMultisig(multisigPlan)
  const message = tx.transaction.message
  requireThat(!message.addressTableLookups?.length && !tx.meta.loadedAddresses?.writable?.length && !tx.meta.loadedAddresses?.readonly?.length)
  requireThat(Array.isArray(message.accountKeys) && Array.isArray(message.instructions) && Array.isArray(review?.top) && Array.isArray(review.inner))
  const keys = message.accountKeys.map(address)
  requireThat(new Set(keys).size === keys.length)
  const decode = i => {
    requireThat(Number.isInteger(i.programIdIndex) && keys[i.programIdIndex] && Array.isArray(i.accounts) && typeof i.data === 'string' &&
      i.accounts.every(k => Number.isInteger(k) && keys[k]))
    return { program: keys[i.programIdIndex], accounts: i.accounts.map(k => keys[k]), data: Buffer.from(bs58.decode(i.data)).toString('hex') }
  }
  requireThat(same(message.instructions.map(decode), [canonical(expected.executeInstruction)]) &&
    same(review.top.map(canonical), [canonical(expected.executeInstruction)]))
  requireThat(tx.meta.innerInstructions?.length === 1 && tx.meta.innerInstructions[0].index === 0 && review.inner.length === 1 && review.inner[0].index === 0)
  const inner = tx.meta.innerInstructions[0].instructions, reviewed = review.inner[0].instructions
  requireThat(inner.length === reviewed.length)
  inner.forEach((i, n) => requireThat(Number.isInteger(i.stackHeight) && i.stackHeight >= 2 && i.stackHeight === reviewed[n].stackHeight &&
    same(decode(i), canonical(reviewed[n].instruction))))
  requireThat(same(inner.filter(i => i.stackHeight === 2).map(decode), plan.instructions.map(canonical)))
  return governance
}

// Explicit reviewed WSOL payout, not a native SOL promise. No unwrap/close/temp key.
// Caller must bind creator beneficiary+boundAt to DB or partner to a separate policy,
// enforce entitlement and collection remaining, and persist signature uniqueness.
export function prepareCustodyPayout({ amount, collectionSignature, beneficiary, beneficiaryBoundAt, partnerRecipientPolicy,
  attribution, payer, createAta = false, collectionItemIndex }) {
  requireThat(typeof amount === 'bigint' && amount > 0n && amount <= 0xffffffffffffffffn && typeof collectionSignature === 'string' && collectionSignature.length > 0)
  requireThat(attribution?.repoId && ['creator', 'partner'].includes(attribution.role))
  requireThat(attribution.phase === 'DBC' ? Number.isInteger(collectionItemIndex) && collectionItemIndex >= 0 && collectionItemIndex < 2
    : collectionItemIndex === undefined && (attribution.phase === undefined || attribution.phase === 'DAMM'))
  const recipient = address(beneficiary)
  requireThat(recipient !== CUSTODY_VAULT)
  if (attribution.role === 'creator') {
    requireThat(typeof beneficiaryBoundAt === 'string' && Number.isFinite(Date.parse(beneficiaryBoundAt)) && !partnerRecipientPolicy)
  } else {
    requireThat(!beneficiaryBoundAt && typeof partnerRecipientPolicy?.id === 'string' && partnerRecipientPolicy.id.length > 0 &&
      partnerRecipientPolicy.repoId === attribution.repoId && address(partnerRecipientPolicy.recipient) === recipient)
  }
  const source = getAssociatedTokenAddressSync(NATIVE_MINT, pk(CUSTODY_VAULT), true)
  const destination = getAssociatedTokenAddressSync(NATIVE_MINT, pk(recipient), true)
  requireThat(!source.equals(destination))
  const transferInstruction = createTransferCheckedInstruction(source, NATIVE_MINT, destination, pk(CUSTODY_VAULT), amount, 9)
  const instructions = createAta ? [createAssociatedTokenAccountIdempotentInstruction(pk(payer), destination, pk(recipient), NATIVE_MINT), transferInstruction] : [transferInstruction]
  return { kind: 'vault-wsol-beneficiary-payout-plan', source: address(source), destination: address(destination), owner: CUSTODY_VAULT,
    mint: address(NATIVE_MINT), beneficiary: recipient, beneficiaryBoundAt: beneficiaryBoundAt ?? null,
    partnerRecipientPolicy: partnerRecipientPolicy ? Object.freeze({ ...partnerRecipientPolicy, recipient }) : null,
    amount, collectionSignature, attribution: Object.freeze({ ...attribution }), payer: address(payer), createAta,
    instructions, transferInstruction, beneficiaryPaid: false,
    ...(attribution.phase === 'DBC' ? { collectionItemIndex } : {}) }
}

export function validateCustodyPayoutReceipt({ plan, tx, finality, review, multisigPlan, governanceProof }) {
  tx = normalizeReceiptTx(tx)
  const expected = prepareCustodyPayout(plan)
  requireThat(plan.source === expected.source && plan.destination === expected.destination &&
    same(plan.instructions.map(canonical), expected.instructions.map(canonical)))
  const governance = validateExecution({ plan: expected, tx, finality, review, multisigPlan, governanceProof })
  requireThat(finality.signature !== expected.collectionSignature)
  const keys = tx.transaction.message.accountKeys.map(address)
  const balance = (rows, account, owner, pre = false) => {
    requireThat(Array.isArray(rows))
    const matches = rows.filter(r => keys[r.accountIndex] === account)
    if (pre && account === expected.destination && matches.length === 0) {
      requireThat(approvedNewAta(expected, tx, keys, account)); return 0n
    }
    requireThat(matches.length === 1)
    const r = matches[0]
    requireThat(r.owner === owner && r.mint === address(NATIVE_MINT) && r.programId === address(TOKEN_PROGRAM_ID) &&
      r.uiTokenAmount?.decimals === 9 && /^(0|[1-9][0-9]*)$/.test(r.uiTokenAmount.amount))
    return BigInt(r.uiTokenAmount.amount)
  }
  requireThat(balance(tx.meta.postTokenBalances, expected.destination, expected.beneficiary) -
    balance(tx.meta.preTokenBalances, expected.destination, expected.beneficiary, true) === expected.amount)
  requireThat(balance(tx.meta.preTokenBalances, expected.source, CUSTODY_VAULT) -
    balance(tx.meta.postTokenBalances, expected.source, CUSTODY_VAULT) === expected.amount)
  return Object.freeze({ kind: 'vault-wsol-beneficiary-payment', signature: finality.signature, slot: tx.slot, amount: expected.amount,
    attribution: expected.attribution, collectionSignature: expected.collectionSignature, beneficiary: expected.beneficiary,
    beneficiaryBoundAt: expected.beneficiaryBoundAt, partnerRecipientPolicy: expected.partnerRecipientPolicy,
    source: expected.source, destination: expected.destination, owner: CUSTODY_VAULT, mint: address(NATIVE_MINT),
    beneficiaryPaid: true, vaultControlVerified: true, governance,
    ...(expected.attribution.phase === 'DBC' ? { collectionItemIndex: expected.collectionItemIndex } : {}) })
}

function normalizeReceiptTx(tx) {
  const m = tx?.transaction?.message
  if (!m?.staticAccountKeys) return tx
  requireThat(Array.isArray(m.compiledInstructions))
  return { ...tx, transaction: { ...tx.transaction, message: { ...m, accountKeys: m.staticAccountKeys,
    instructions: m.compiledInstructions.map(i => ({ programIdIndex: i.programIdIndex, accounts: Array.from(i.accountKeyIndexes),
      data: bs58.encode(i.data) })) } } }
}

// Internal service boundary, NOT a request/JSON endpoint: evidence and the reviewed
// plan must be assembled from trusted RPC and review storage. Validation cannot
// establish provenance of arbitrary user JSON. Supply a pool or an idle client;
// these wrappers own the entire SQL transaction (do not nest in a caller's BEGIN).
async function recordValidated(db, evidence, payout, dbcBatch = false) {
  const receipt = dbcBatch ? validateDbcCustodyBatchReceipt(evidence) :
    payout ? validateCustodyPayoutReceipt(evidence) : validateCustodyReceipt(evidence)
  const { recordCustodyCollection, recordCustodyPayout, recordDbcCustodyBatchCollection } = await import('./custody-ledger.mjs')
  // pg.Client also has connect(); only pg.Pool exposes totalCount.
  const owned = typeof db.connect === 'function' && typeof db.totalCount === 'number'
  const client = owned ? await db.connect() : db
  try {
    await client.query('BEGIN')
    const result = dbcBatch ? await recordDbcCustodyBatchCollection(client, receipt) : payout ? await recordCustodyPayout(client, receipt, {
      partnerBeneficiary: receipt.attribution.role === 'partner' ? receipt.partnerRecipientPolicy.recipient : null,
    }) : await recordCustodyCollection(client, receipt)
    await client.query('COMMIT')
    return { ...result, receipt }
  } catch (error) {
    await client.query('ROLLBACK')
    throw error
  } finally { if (owned) client.release() }
}

export const recordValidatedCustodyCollection = (db, evidence) => recordValidated(db, evidence, false)
export const recordValidatedCustodyPayout = (db, evidence) => recordValidated(db, evidence, true)
export const recordValidatedDbcCustodyBatchCollection = (db, evidence) => recordValidated(db, evidence, false, true)
